#!/usr/bin/env python3
"""Agent Bridge CLI for interacting with a running MindFusion Studio server."""

import argparse
import json
import os
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path
from typing import Any, Dict


def api_request(base_url: str, path: str, method: str = "GET", payload: Dict[str, Any] | None = None, timeout: int = 15) -> Dict[str, Any]:
    url = f"{base_url.rstrip('/')}{path}"
    data = json.dumps(payload).encode("utf-8") if payload is not None else None
    headers = {"Content-Type": "application/json"} if payload is not None else {}
    req = urllib.request.Request(url, data=data, headers=headers, method=method)
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        return json.loads(resp.read().decode("utf-8"))


AGENT_NAME = os.environ.get("MINDFUSION_AGENT_NAME", "Agent")


def cmd_status(base_url: str) -> None:
    api_request(base_url, "/api/agent/heartbeat", method="POST", payload={
        "agent_name": AGENT_NAME,
        "mode": "agent_bridge",
    })
    state = api_request(base_url, "/api/state")
    active_id = state.get("active_node_id")
    active_node = state.get("nodes", {}).get(active_id, {})
    pending = [j for j in state.get("jobs", {}).values() if j.get("status") in ("pending", "denoising")]

    summary = {
        "active_node_id": active_id,
        "total_versions": len(state.get("nodes", {})),
        "active_version": {
            "id": active_node.get("id"),
            "version_num": active_node.get("version_num"),
            "label": active_node.get("label"),
            "title": active_node.get("title"),
            "seed_outline": active_node.get("seed_outline"),
            "content": active_node.get("content"),
            "draft": active_node.get("draft"),  # unsaved hand edits on top of content, if any
            "active_comments": [c for c in active_node.get("comments", []) if not c.get("resolved")],
            "params": active_node.get("params"),
        },
        "pending_jobs": pending,
    }
    print(json.dumps(summary, indent=2))


def cmd_push(base_url: str, args: argparse.Namespace) -> None:
    if args.content_file:
        content = Path(args.content_file).read_text(encoding="utf-8")
    elif args.content:
        content = args.content
    else:
        content = sys.stdin.read()

    state = api_request(base_url, "/api/state")
    parent_id = args.parent_id or state.get("active_node_id")

    # Check if there is a pending job to complete
    pending = [j for j in state.get("jobs", {}).values() if j.get("status") in ("pending", "denoising")]
    job_id = args.job_id or (pending[-1]["id"] if pending else None)

    if not job_id:
        # Create a synthetic job on the server and complete it immediately
        parent_node = state.get("nodes", {}).get(parent_id, {})
        gen_res = api_request(base_url, "/api/generate", method="POST", payload={
            "parent_id": parent_id,
            "seed_outline": parent_node.get("seed_outline", ""),
            "content": parent_node.get("content", ""),
            "comments": parent_node.get("comments", []),
            "params": {**(parent_node.get("params") or {}), "provider": "agent_bridge"},
        })
        job_id = gen_res["job"]["id"]

    res = api_request(base_url, "/api/agent/complete", method="POST", payload={
        "job_id": job_id,
        "content": content,
        "title": args.title,
        "label": args.label,
        "diff_summary": args.summary or f"Generated by {AGENT_NAME}",
        "provider_used": f"{AGENT_NAME} (live session)",
    })
    print(json.dumps({"completed_job": job_id, "new_node": res.get("node")}, indent=2))


def cmd_poll(base_url: str) -> None:
    res = api_request(base_url, "/api/agent/pending?" + urllib.parse.urlencode({"agent": AGENT_NAME, "mode": "agent_bridge"}))
    print(json.dumps(res, indent=2))


def cmd_listen(base_url: str, timeout: int = 3600) -> None:
    """Blocks until the user taps 'Diffuse' in the web UI, then prints the job JSON and exits 0 (waking the active agent session)."""
    while True:
        try:
            query = urllib.parse.urlencode({"timeout": min(timeout, 300), "agent": AGENT_NAME})
            res = api_request(base_url, f"/api/agent/wait?{query}", timeout=min(timeout, 300) + 15)
            jobs = res.get("pending_jobs", [])
            if jobs:
                print(json.dumps({"event": "DIFFUSE_REQUESTED", "jobs": jobs}, indent=2))
                sys.stdout.flush()
                return
        except Exception:
            time.sleep(1.0)


def main() -> None:
    parser = argparse.ArgumentParser(description="MindFusion Agent Bridge CLI")
    parser.add_argument("--url", default=os.environ.get("MINDFUSION_URL", "http://127.0.0.1:8765"), help="MindFusion server URL")
    parser.add_argument("--agent-name", default=None, help="Name shown in the UI for this agent (e.g. 'Claude Code'); env MINDFUSION_AGENT_NAME")
    sub = parser.add_subparsers(dest="cmd", required=True)

    sub.add_parser("status", help="Send agent heartbeat and inspect active canvas node, comments, and pending jobs")
    sub.add_parser("poll", help="Check for pending generation jobs queued for the agent")
    listen_p = sub.add_parser("listen", help="Long-poll listener: blocks until user clicks Diffuse, then wakes this agent session")
    listen_p.add_argument("--timeout", type=int, default=3600, help="Max wait seconds")

    push_p = sub.add_parser("push", help="Push a polished agent generation into the MindFusion version tree")
    push_p.add_argument("--job-id", help="Optional specific job ID to complete")
    push_p.add_argument("--parent-id", help="Optional parent version node ID to branch from")
    push_p.add_argument("--title", help="Document title for the new version")
    push_p.add_argument("--label", help="Version badge label (e.g. 'v2 · Agent Polish')")
    push_p.add_argument("--summary", help="Summary of changes in this generation")
    push_p.add_argument("--content", help="Inline HTML content string")
    push_p.add_argument("--content-file", help="Path to an HTML fragment file containing the generated content")

    args = parser.parse_args()
    global AGENT_NAME
    if args.agent_name:
        AGENT_NAME = args.agent_name
    if args.cmd == "status":
        cmd_status(args.url)
    elif args.cmd == "poll":
        cmd_poll(args.url)
    elif args.cmd == "listen":
        cmd_listen(args.url, args.timeout)
    elif args.cmd == "push":
        cmd_push(args.url, args)


if __name__ == "__main__":
    main()
